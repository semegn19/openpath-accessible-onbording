/**
 * Builds the list of spoken strings, the file names they need, and the index the app reads.
 *
 *   node scripts/audio-manifest.mjs            # write public/audio/index.json + the checklist
 *   node scripts/audio-manifest.mjs --list     # print what is still missing, no writes
 *
 * Files are named by an FNV-1a hash of "<lang>|<text>" so a recording never has to be renamed by
 * hand and never collides. Drop `public/audio/<name>.opus` in place, re-run this, and the app
 * plays it — no code change, no rebuild of the strings.
 *
 * Record with a human (best) or generate once with an open model at build time (see
 * docs/amharic-voice.md). Nothing here calls the network: the runtime never leaves the origin.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { collect, FORMS } from './_strings.mjs';

const SCHEMA_DIR = fileURLToPath(new URL('../../schema/', import.meta.url));
const AUDIO_DIR = fileURLToPath(new URL('../public/audio/', import.meta.url));
const DOC = fileURLToPath(new URL('../../docs/audio-recording-list.md', import.meta.url));

/** FNV-1a 32-bit. Identical to clipName() in src/audio.ts — change both or neither. */
const hash = (s) => {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
};

// One collector, shared with the tests: this file used to carry its own copy of the walk, and the
// two silently drifted — the simple-words strings were added to one and not the other, so the
// recording checklist would have shipped missing 64 clips.
const strings = collect(SCHEMA_DIR);

// Collect all known step IDs across schemas so pre-recorded step audio is recognized
const knownSteps = new Set();
for (const form of FORMS) {
  try {
    const schema = JSON.parse(readFileSync(join(SCHEMA_DIR, `${form}.json`), 'utf8'));
    for (const step of schema.steps ?? []) {
      if (step.id) knownSteps.add(step.id);
    }
  } catch {}
}

const parseStepAudio = (f) => {
  const m = f.match(/^(?:([a-z0-9-]+)_)?([a-z0-9-]+)[._](am|en|om|ti)(?:\.(simple))?\.[a-z0-9]+$/i);
  if (!m) return null;
  const [, formPrefix, stepId, lang, simple] = m;
  if (!knownSteps.has(stepId)) return null;
  return { formPrefix, stepId, lang: lang.toLowerCase(), simple: Boolean(simple) };
};

mkdirSync(AUDIO_DIR, { recursive: true });
const present = new Set(readdirSync(AUDIO_DIR).filter((f) => /\.(opus|ogg|mp3|m4a|wav)$/i.test(f)));

const index = {};
const missing = [];
for (const s of strings) {
  const name = hash(`${s.lang}|${s.text}`);
  const file = [...present].find((f) => f.replace(/\.[^.]+$/, '') === name);
  if (file) index[name] = file;
  else missing.push({ ...s, name, target: `${name}.opus` });
}

// Index any pre-recorded step audio files (<stepId>.<lang>.<ext> or <form>_<stepId>.<lang>.<ext>)
for (const f of present) {
  const parsed = parseStepAudio(f);
  if (parsed) {
    const { formPrefix, stepId, lang, simple } = parsed;
    index[`${stepId}:${lang}${simple ? ':simple' : ''}`] = f;
    index[`${stepId}.${lang}${simple ? '.simple' : ''}`] = f;
    if (formPrefix) {
      index[`${formPrefix}:${stepId}:${lang}${simple ? ':simple' : ''}`] = f;
    }
  }
}

// a clip for a string that no longer exists is dead weight — say so rather than ship it
const orphans = [...present].filter((f) => {
  const byString = strings.some((s) => hash(`${s.lang}|${s.text}`) === f.replace(/\.[^.]+$/, ''));
  const byStep = Boolean(parseStepAudio(f));
  return !byString && !byStep;
});

if (process.argv.includes('--list')) {
  console.log(`${strings.length} spoken strings · ${present.size} files · ${strings.length - missing.length} covered`);
  for (const m of missing) console.log(`  ${m.target}  ${m.lang}  ${m.text.slice(0, 60)}`);
  process.exit(0);
}

writeFileSync(new URL('../public/audio/index.json', import.meta.url), JSON.stringify(index, null, 0) + '\n');
writeFileSync(new URL('../src/audio-index.json', import.meta.url), JSON.stringify(index, null, 0) + '\n');

const bytes = [...present].reduce((n, f) => n + statSync(join(AUDIO_DIR, f)).size, 0);
const lines = [
  '# Recording list — Amharic read-aloud',
  '',
  `Generated by \`npm run audio\` on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
  '',
  `**${strings.length} strings · ${strings.length - missing.length} recorded · ${missing.length} missing · ${(bytes / 1024 / 1024).toFixed(2)} MB of audio in the repo**`,
  '',
  'Record each string, save it as the file name in the first column, drop it in `app/public/audio/`,',
  'then run `npm run audio` again. Format: **m4a (AAC), mono, 32 kbit/s** — the one format every phone plays, iOS included:`ffmpeg -i in.wav -c:a aac -b:a 32k -ac 1 out.m4a`.',
  'which is roughly 3 KB per second of speech — a 10-second question is about 30 KB.',
  '',
  '## Missing',
  '',
  '| File | Lang | Where | Text |',
  '|---|---|---|---|',
  ...missing.map((m) => `| \`${m.target}\` | ${m.lang} | ${m.form.replace('savanna-', '').replace('-v1', '')} · ${m.where} | ${m.text.replace(/\|/g, '\\|')} |`),
  '',
];
if (orphans.length) {
  lines.push('## Files with no matching string (delete these)', '', ...orphans.map((f) => `- \`${f}\``), '');
}
writeFileSync(DOC, lines.join('\n'));

console.log(`spoken strings: ${strings.length}`);
console.log(`covered:        ${strings.length - missing.length}`);
console.log(`missing:        ${missing.length}`);
if (orphans.length) console.log(`orphans:        ${orphans.length} (see ${DOC})`);
console.log(`index →         public/audio/index.json (${Object.keys(index).length} clips)`);

/**
 * Recorded audio first, device voice second, an honest message third.
 *
 * Why recorded first. Amharic TTS is not on the phone. Google Text-to-Speech, the engine on
 * almost every Android device, has no Amharic voice at all — the only Android engine that does
 * is eSpeak, which the user has to install. So `speechSynthesis` in `am` returns nothing on the
 * target device, and "read aloud" silently does not work for the people who need it most.
 *
 * The fix is not a paid API (that breaks the offline promise and the cost promise) and not
 * hoping the device has a voice. It is shipping the sound: the questions, hints and consent
 * statements are a closed set of ~70 strings, so they can be recorded once — by a human, or
 * generated once by an open model at build time — and served as small files. They work offline,
 * on any phone, with no data cost and no third-party request.
 *
 * Dynamic text (a name read back on the review screen) cannot be pre-recorded, so it falls back
 * to the device voice, and if there is none the UI says so instead of pretending.
 *
 * The index is generated by `npm run audio` (scripts/audio-manifest.mjs). A missing index, a
 * missing file or a failed play all fall through to the fallback — never to silence.
 */
import type { Lang } from './types';

/** FNV-1a, 32-bit. Duplicated in scripts/audio-manifest.mjs — must stay identical. */
const hash = (s: string): string => {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
};

/** Stable name for one spoken string: language + exact text. */
export const clipName = (lang: Lang, text: string): string => hash(`${lang}|${text.trim()}`);

type Index = Record<string, string>;          // clipName → file name in /audio/
let index: Index | null = null;
let loading: Promise<void> | null = null;
let current: HTMLAudioElement | null = null;

async function load(): Promise<void> {
  if (index || loading) return loading ?? Promise.resolve();
  loading = fetch('/audio/index.json', { cache: 'force-cache' })
    .then((r) => (r.ok ? r.json() : {}))
    .then((j: unknown) => { index = (j && typeof j === 'object' ? j : {}) as Index; })
    .catch(() => { index = {}; })
    .finally(() => { loading = null; });
  return loading;
}

export function stopAudio(): void {
  if (current) {
    try { current.pause(); current.currentTime = 0; } catch { /* already gone */ }
    current = null;
  }
}

/** Play the recorded clip for this text. False means "no clip", not "it failed badly". */
export async function playRecorded(lang: Lang, text: string): Promise<boolean> {
  await load();
  const file = index?.[clipName(lang, text)];
  if (!file) return false;
  stopAudio();
  try {
    const el = new Audio(`/audio/${file}`);
    el.preload = 'auto';
    current = el;
    await el.play();
    return true;
  } catch {
    return false;      // autoplay refusal, decode error, 404 — fall through, never silent
  }
}

/** How many clips this build actually ships. Used by the UI and by tests. */
export async function clipCount(): Promise<number> {
  await load();
  return Object.keys(index ?? {}).length;
}

// One form per page, at a real path: /onboard, /job, /employer. No top navigation.
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { AxeBuilder } from '@axe-core/playwright';

// The brand is the form's own title. Read it from the schema rather than hardcoding it —
// a grammar fix in the copy should not fail a routing test, and a hardcoded string here
// is one more place the title can go stale.
// Read the canonical schema, not the generated copy in src/schemas: a test that depends on build
// output fails on a clean clone, and src/schemas is regenerated by `npm run sync:schemas`.
const titleOf = (f) => JSON.parse(readFileSync(new URL(`../../schema/${f}`, import.meta.url))).title.am;
const onboardTitle = titleOf('savanna-onboard-v1.json');
const jobTitle = titleOf('savanna-job-v1.json');
const employerTitle = titleOf('employer-accommodations-v1.json');

const ORIGIN = process.env.ORIGIN || 'http://127.0.0.1:5173';
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 390, height: 844 } });
const p = await c.newPage();
let fail = 0;
const ok = (cond, label, extra = '') => { if (!cond) fail++; console.log(`${cond ? '✓' : '✗'} ${label}${extra ? ' → ' + extra : ''}`); };

const axe = async (label) => {
  const { violations } = await new AxeBuilder({ page: p }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze();
  const bad = violations.filter((v) => ['critical', 'serious'].includes(v.impact));
  if (bad.length) fail++;
  console.log(`${bad.length ? '✗' : '✓'} ${label.padEnd(24)} serious/critical: ${bad.length}${bad.length ? ' → ' + bad.map((v) => v.id) : ''}`);
};

const PAGES = [
  ['/onboard', onboardTitle, 'ቋንቋ ይምረጡ'],
  ['/job', jobTitle, null],
  ['/employer', employerTitle, null],
];

for (const [path, brand, firstQuestion] of PAGES) {
  const res = await p.goto(ORIGIN + path, { waitUntil: 'networkidle' });
  const got = (await p.locator('.op-brand').innerText()).trim();
  const h1 = (await p.locator('h1').first().innerText()).trim();
  ok(res.status() === 200 && got === brand, `GET ${path}`, `${res.status()} "${got}"`);
  ok(await p.locator('.op-forms, nav').count() === 0, `  no top navigation on ${path}`);
  ok((await p.title()).startsWith(brand), `  page title`, await p.title());
  ok((await p.evaluate(() => location.pathname)) === path, `  address bar stays`, await p.evaluate(() => location.pathname));
  if (firstQuestion) ok(h1 === firstQuestion, '  first question', h1);
  await axe(`page ${path}`);
}

// bare domain lands on the portal landing page
await p.goto(ORIGIN + '/', { waitUntil: 'networkidle' });
ok((await p.evaluate(() => location.pathname)) === '/', 'bare domain lands on /', await p.evaluate(() => location.pathname));
const cards = await p.locator('.op-landing-card').all();
ok(cards.length === 3, 'landing page offers 3 gateway cards', String(cards.length));
await axe('page / (landing portal)');

// an old #/job link that someone already shared keeps working, and is cleaned up
await p.goto(ORIGIN + '/#/job', { waitUntil: 'networkidle' });
ok((await p.locator('.op-brand').innerText()).trim() === jobTitle, 'old #/job link still works');
ok((await p.evaluate(() => location.pathname + location.hash)) === '/job', '  and is rewritten to /job', await p.evaluate(() => location.pathname + location.hash));

// the skip link must not be mistaken for a route change
await p.goto(ORIGIN + '/employer', { waitUntil: 'networkidle' });
await p.keyboard.press('Tab');
const firstTab = await p.evaluate(() => document.activeElement?.textContent?.trim());
await p.keyboard.press('Enter');
await p.waitForTimeout(200);
const after = await p.evaluate(() => ({ focus: document.activeElement?.id, path: location.pathname, brand: document.querySelector('.op-brand')?.textContent?.trim() }));
ok(after.focus === 'op-main' && after.path === '/employer' && after.brand === employerTitle,
   'skip link keeps the page', `tab="${firstTab}" focus=${after.focus} path=${after.path}`);

// back/forward across pages
await p.goto(ORIGIN + '/onboard', { waitUntil: 'networkidle' });
await p.goto(ORIGIN + '/job', { waitUntil: 'networkidle' });
await p.goBack(); await p.waitForTimeout(300);
ok((await p.locator('.op-brand').innerText()).trim() === onboardTitle, 'browser back', await p.evaluate(() => location.pathname));

/* ---------- branching: fayda & kebele ask for photo, refer asks for partner consent ---------- */
const walk = async (routeIndex) => {
  await p.goto(ORIGIN + '/onboard', { waitUntil: 'load' });
  await p.evaluate(() => localStorage.clear());
  await p.reload({ waitUntil: 'load' });
  const next = () => p.getByRole('button', { name: /^ቀጣይ$|^ላክ$/ }).first().click({ timeout: 2000 });
  await p.locator('.op-option input').first().check({ timeout: 2000 });
  await next(); await p.waitForTimeout(120);                       // language
  await next(); await p.waitForTimeout(120);                       // preferences
  for (const v of ['ሳራ በቀለ', '0912345678']) {
    await p.locator('.op-input').first().fill(v, { timeout: 2000 });
    await next(); await p.waitForTimeout(150);                     // name, phone
  }
  await p.locator('.op-option input').nth(routeIndex).check({ timeout: 2000 });   // 0: fayda, 2: kebele, 4: refer
  await next(); await p.waitForTimeout(250);
  return {
    type: await p.locator('.op-root').getAttribute('data-step-type'),
    heading: (await p.locator('#op-q-title').innerText()).replace(/\s+/g, ' '),
    progress: (await p.locator('.op-progress').innerText()).replace(/\s+/g, ' '),
  };
};
const pickedFayda = await walk(0);
ok(pickedFayda.type === 'file',
   'choosing Fayda asks for photo upload (file)', `${pickedFayda.type}: ${pickedFayda.heading}`);
const pickedKebele = await walk(2);
ok(pickedKebele.type === 'file',
   'choosing Kebele ID asks for photo upload (file)', `${pickedKebele.type}: ${pickedKebele.heading}`);
const pickedPartner = await walk(4);
ok(pickedPartner.type === 'statement',
   'choosing partner referral shows consent statement', `${pickedPartner.type}: ${pickedPartner.heading}`);

await b.close();
console.log(`\n${fail ? 'FAIL' : 'PASS'} — ${fail} problem(s)`);
process.exit(fail ? 1 : 0);
